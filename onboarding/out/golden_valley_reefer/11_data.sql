-- =====================================================================
-- Golden Valley Reefer · 11_data.sql · Lanes, cost basis, example customers
-- Run after 10_policy.sql. Does NOT touch FUEL_INDEX (shared diesel).
-- Carrier cost per mile values are ILLUSTRATIVE ESTIMATES (not audited).
-- Customers are fictional; ids use the GVR- prefix to avoid collisions.
-- =====================================================================
USE ROLE BROKER_ADMIN;
USE WAREHOUSE COUNTEROFFER_WH;
USE DATABASE COUNTEROFFER;

MERGE INTO COUNTEROFFER.PUBLIC.LANES t
USING (
  SELECT 'SNS-CHI' AS LANE_ID, 'Salinas' AS ORIGIN_CITY, 'CA' AS ORIGIN_STATE, 'Chicago' AS DEST_CITY, 'IL' AS DEST_STATE, 2130 AS MILES, 'REEFER' AS EQUIPMENT
  UNION ALL SELECT 'SNS-ATL', 'Salinas', 'CA', 'Atlanta',  'GA', 2450, 'REEFER'
  UNION ALL SELECT 'SNS-DAL', 'Salinas', 'CA', 'Dallas',   'TX', 1640, 'REEFER'
  UNION ALL SELECT 'SNS-NYC', 'Salinas', 'CA', 'New York', 'NY', 2950, 'REEFER'
  UNION ALL SELECT 'FRE-CHI', 'Fresno',  'CA', 'Chicago',  'IL', 2000, 'REEFER'
  UNION ALL SELECT 'FRE-ATL', 'Fresno',  'CA', 'Atlanta',  'GA', 2300, 'REEFER'
  UNION ALL SELECT 'FRE-DAL', 'Fresno',  'CA', 'Dallas',   'TX', 1480, 'REEFER'
  UNION ALL SELECT 'FRE-NYC', 'Fresno',  'CA', 'New York', 'NY', 2800, 'REEFER'
) s
ON t.LANE_ID = s.LANE_ID
WHEN MATCHED THEN UPDATE SET
  ORIGIN_CITY = s.ORIGIN_CITY, ORIGIN_STATE = s.ORIGIN_STATE,
  DEST_CITY = s.DEST_CITY, DEST_STATE = s.DEST_STATE,
  MILES = s.MILES, EQUIPMENT = s.EQUIPMENT
WHEN NOT MATCHED THEN INSERT (LANE_ID, ORIGIN_CITY, ORIGIN_STATE, DEST_CITY, DEST_STATE, MILES, EQUIPMENT)
  VALUES (s.LANE_ID, s.ORIGIN_CITY, s.ORIGIN_STATE, s.DEST_CITY, s.DEST_STATE, s.MILES, s.EQUIPMENT);

MERGE INTO COUNTEROFFER.PRIVATE.COST_BASIS t
USING (
  SELECT 'SNS-CHI' AS LANE_ID, 2.50 AS CARRIER_COST_PER_MILE
  UNION ALL SELECT 'SNS-ATL', 2.40
  UNION ALL SELECT 'SNS-DAL', 2.70
  UNION ALL SELECT 'SNS-NYC', 2.30
  UNION ALL SELECT 'FRE-CHI', 2.45
  UNION ALL SELECT 'FRE-ATL', 2.35
  UNION ALL SELECT 'FRE-DAL', 2.65
  UNION ALL SELECT 'FRE-NYC', 2.25
) s
ON t.LANE_ID = s.LANE_ID
WHEN MATCHED THEN UPDATE SET CARRIER_COST_PER_MILE = s.CARRIER_COST_PER_MILE
WHEN NOT MATCHED THEN INSERT (LANE_ID, CARRIER_COST_PER_MILE) VALUES (s.LANE_ID, s.CARRIER_COST_PER_MILE);

MERGE INTO COUNTEROFFER.PUBLIC.CUSTOMERS t
USING (
  SELECT 'GVR-C01' AS CUSTOMER_ID, 'Harvest Table Markets' AS NAME, 'STRATEGIC' AS TIER, 1840 AS LIFETIME_LOADS, 28 AS AVG_DAYS_TO_PAY
  UNION ALL SELECT 'GVR-C02', 'Sierra Sun Growers',            'PREFERRED', 620, 21
  UNION ALL SELECT 'GVR-C03', 'Bluebonnet Fresh Distributors', 'PREFERRED', 410, 30
  UNION ALL SELECT 'GVR-C04', 'Lakeshore Produce Co.',         'STANDARD',  45,  38
  UNION ALL SELECT 'GVR-C05', 'Peachtree Greens',              'STANDARD',  12,  35
) s
ON t.CUSTOMER_ID = s.CUSTOMER_ID
WHEN MATCHED THEN UPDATE SET NAME = s.NAME, TIER = s.TIER, LIFETIME_LOADS = s.LIFETIME_LOADS, AVG_DAYS_TO_PAY = s.AVG_DAYS_TO_PAY
WHEN NOT MATCHED THEN INSERT (CUSTOMER_ID, NAME, TIER, LIFETIME_LOADS, AVG_DAYS_TO_PAY)
  VALUES (s.CUSTOMER_ID, s.NAME, s.TIER, s.LIFETIME_LOADS, s.AVG_DAYS_TO_PAY);

SELECT l.LANE_ID, l.ORIGIN_CITY, l.DEST_CITY, l.MILES, l.EQUIPMENT, c.CARRIER_COST_PER_MILE
FROM COUNTEROFFER.PUBLIC.LANES l
JOIN COUNTEROFFER.PRIVATE.COST_BASIS c ON c.LANE_ID = l.LANE_ID
WHERE l.LANE_ID LIKE 'SNS-%' OR l.LANE_ID LIKE 'FRE-%'
ORDER BY l.LANE_ID;
SELECT * FROM COUNTEROFFER.PUBLIC.CUSTOMERS WHERE CUSTOMER_ID LIKE 'GVR-%' ORDER BY CUSTOMER_ID;
